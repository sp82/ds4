#!/usr/bin/env python3
"""Generate the vkbench SPIR-V C headers from the HLSL sources.

Mirrors vulkan/shaders/gen_shaders.py: compiles each .hlsl with dxc
(HLSL -> SPIR-V) and emits a C header with the byte array.  Binding layout
matches vkbench.c: t0 -> 0 (a), t1 -> 1 (b), u0 -> 2 (out).

Usage: python3 gen_vkbench_shaders.py
Requires: dxc on PATH (or DXC env var), python3.
Output:   vulkan/tools/vkbench/{saxpy,madloop}_spv.h  (committed)
"""
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def find_dxc():
    exe = os.environ.get("DXC", "dxc")
    if shutil.which(exe):
        return exe
    sys.stderr.write("gen_vkbench_shaders.py: dxc not found "
                     "(set DXC or add it to PATH)\n")
    sys.exit(1)


def compile_spv(dxc, src, entry, out_spv):
    cmd = [dxc, "-T", "cs_6_0", "-E", entry, "-spirv",
           "-fspv-target-env=vulkan1.0",
           "-fvk-t-shift", "0", "0",
           "-fvk-u-shift", "2", "0",
           "-fvk-b-shift", "8", "0",
           "-Fo", out_spv, src]
    subprocess.check_call(cmd)


def emit_header(spv, header, ident):
    data = open(spv, "rb").read()
    with open(header, "w") as f:
        f.write("/* generated by gen_vkbench_shaders.py; do not edit */\n")
        f.write("#include <stdint.h>\n")
        f.write("static const unsigned char %s[] = {\n" % ident)
        for i in range(0, len(data), 12):
            f.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) +
                    ",\n")
        f.write("};\n")
        f.write("static const size_t %s_len = sizeof(%s);\n" % (ident, ident))
    os.unlink(spv)


def main():
    dxc = find_dxc()
    spv = os.path.join("/tmp", "vkbench_spv_tmp.bin")
    compile_spv(dxc, os.path.join(HERE, "saxpy.hlsl"), "saxpy", spv)
    emit_header(spv, os.path.join(HERE, "saxpy_spv.h"), "saxpy_spv")
    compile_spv(dxc, os.path.join(HERE, "madloop.hlsl"), "madloop", spv)
    emit_header(spv, os.path.join(HERE, "madloop_spv.h"), "madloop_spv")
    sys.stderr.write("gen_vkbench_shaders.py: wrote saxpy_spv.h + "
                     "madloop_spv.h\n")


if __name__ == "__main__":
    main()
